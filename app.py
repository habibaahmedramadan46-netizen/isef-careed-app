# نموذج الأسئلة
with st.form("career_test_form"):
    scores = {"علوم": 0, "رياضة": 0, "تكنولوجيا": 0, "أدبي": 0}
    max_scores = {"علوم": 40, "رياضة": 40, "تكنولوجيا": 35, "أدبي": 35}

    for i, item in enumerate(questions):
        ans = st.radio(
            item["q"],
            list(options.keys()),
            index=2,
            key=f"q_{i}",
            horizontal=True
        )
        scores[item["track"]] += options[ans]
        st.markdown("---")

    submitted = st.form_submit_button("🔍 اكتشف مساري الدراسي الآن", use_container_width=True)

# عرض النتيجة
if submitted:
    # حساب النسب المئوية لكل مسار
    percentages = {
        "علمي علوم (الطب والصيدلة والعلوم الحيوية)": round((scores["علوم"] / max_scores["علوم"]) * 100, 1),
        "علمي رياضة (الهندسة والفيزياء والرياضيات)": round((scores["رياضة"] / max_scores["رياضة"]) * 100, 1),
        "التكنولوجيا والبرمجة والذكاء الاصطناعي": round((scores["تكنولوجيا"] / max_scores["تكنولوجيا"]) * 100, 1),
        "المسار الأدبي (العلوم الإنسانية والقانون والإعلام)": round((scores["أدبي"] / max_scores["أدبي"]) * 100, 1)
    }

    best_track = max(percentages, key=percentages.get)
    best_score = percentages[best_track]

    st.success(f"🎉 المسار الأنسب لقدراتك وميولك هو: **{best_track}** بنسبة توافق **{best_score}%**")

